function deriveResume(steps) {
  const running = steps.filter((step) => step.state === "running");
  const cleanup = steps.find((step) => step.state === "cleanup-required");
  const failed = steps.find((step) => step.state === "failed");
  if (running.length > 0) {
    return {
      allowed: false,
      action: "reconcile",
      stepId: running[0].id,
      reason: "A running step must be reconciled before retry or resume.",
    };
  }
  if (cleanup) {
    return {
      allowed: false,
      action: "cleanup",
      stepId: cleanup.id,
      reason: "Cleanup review and separate approval are required before resume.",
    };
  }
  if (failed) {
    const retryable = failed.retryable && failed.attempt < failed.maxAttempts;
    return {
      allowed: retryable,
      action: retryable ? "retry" : "cleanup",
      stepId: failed.id,
      reason: retryable
        ? "The failed idempotent step may be retried with unchanged artifact digests."
        : "The failed step exhausted retries or is not retryable; cleanup review is required.",
    };
  }
  const next = steps.find((step) => step.state === "pending");
  if (!next) {
    return {
      allowed: false,
      action: "complete",
      stepId: null,
      reason: "All ordered steps succeeded.",
    };
  }
  if (next.order === 1) {
    return {
      allowed: false,
      action: "start",
      stepId: next.id,
      reason: "A future executor may start only after a signed secondary approval exists.",
    };
  }
  return {
    allowed: true,
    action: "resume",
    stepId: next.id,
    reason: "Resume at the first pending step with unchanged idempotency and artifact digests.",
  };
}

function validateStepStateSemantics(manifest) {
  const steps = manifest.steps;
  if (
    steps.some((step, index) => step.order !== index + 1) ||
    new Set(steps.map((step) => step.id)).size !== steps.length
  ) {
    throw new Error("Deployment steps must be uniquely and contiguously ordered.");
  }
  if (steps.filter((step) => step.state === "running").length > 1) {
    throw new Error("Only one deployment step may be running.");
  }
  const activeIndex = steps.findIndex((step) => step.state !== "succeeded");
  if (
    activeIndex >= 0 &&
    steps.slice(0, activeIndex).some((step) => step.state !== "succeeded")
  ) {
    throw new Error("Steps before the active step must have succeeded.");
  }
  if (
    activeIndex >= 0 &&
    steps
      .slice(activeIndex + 1)
      .some((step) => step.state !== "pending")
  ) {
    throw new Error("Steps after the active step must remain pending.");
  }
  const expected = deriveResume(steps);
  if (canonicalJson(expected) !== canonicalJson(manifest.resume)) {
    throw new Error("The resume decision does not match the durable step state.");
  }
  return expected;
}

function validateStepTransition(previous, current) {
  if (
    previous.provider !== current.provider ||
    previous.manifestDigest === current.manifestDigest
  ) {
    throw new Error("A state transition requires the same provider and a new manifest digest.");
  }
  const changed = current.steps.filter(
    (step, index) =>
      canonicalJson(step) !== canonicalJson(previous.steps[index]),
  );
  if (changed.length !== 1) {
    throw new Error("Exactly one ordered step may change per persisted transition.");
  }
  const next = changed[0];
  const prior = previous.steps.find((step) => step.id === next.id);
  const allowed = new Set([
    "pending:running",
    "running:succeeded",
    "running:failed",
    "running:cleanup-required",
    "failed:running",
    "failed:cleanup-required",
  ]);
  if (!allowed.has(`${prior.state}:${next.state}`)) {
    throw new Error(`Unsupported step transition: ${prior.state} -> ${next.state}.`);
  }
  if (
    prior.state === "failed" &&
    next.state === "running" &&
    (!prior.retryable || prior.attempt >= prior.maxAttempts)
  ) {
    throw new Error("The failed step is not eligible for retry.");
  }
  validateStepStateSemantics(current);
}

function buildManifest(plan, artifact, outputDirectory) {
  const names = resourceNames(plan);
  const subscription = plan.decisionModel.target.environments.find(
    (item) => item.name === "nonprod",
  ).subscriptionId;
  const stateIdentifier =
    artifact.provider === "terraform"
      ? artifact.stateKey
      : `deployment:cool-nonprod-${artifact.region}`;
  const primaryIdentifier =
    artifact.provider === "terraform"
      ? artifact.stateKey.replace("-secondary.tfstate", "-primary.tfstate")
      : `deployment:primary-nonprod-${plan.decisionModel.regional.primary.region}`;
  const steps = stepDefinitions(
    artifact.provider,
    plan.planDigest,
    artifact.digest,
  );
  const document = {
    schemaVersion: MANIFEST_VERSION,
    manifestVersion: MANIFEST_VERSION,
    generatedBy: GENERATED_BY,
    manifestDigest: hashCanonical({ placeholder: artifact.provider }),
    provider: artifact.provider,
    mode: "cool-infrastructure",
    environment: "nonprod",
    sourcePlan: {
      schemaVersion: plan.schemaVersion,
      planId: plan.planId,
      planDigest: plan.planDigest,
      readinessEvidenceDigest: plan.readinessEvidence.evidenceDigest,
    },
    target: {
      tenantId: plan.decisionModel.target.tenantId,
      subscriptionId: subscription,
      regionRole: "secondary",
      region: artifact.region,
      scope: `/subscriptions/${subscription}/resourceGroups/${names.networkingResourceGroup}`,
      primaryVnetCidr: plan.decisionModel.regional.primary.vnetCidr,
      secondaryVnetCidr: plan.decisionModel.regional.secondary.vnetCidr,
      resourceNames: names,
    },
    artifacts: {
      parameterPath: artifact.path,
      parameterDigest: artifact.digest,
      decisionDigest: artifact.decisionDigest,
      sourcePath: artifact.sourcePath,
      sourceDigest: sourceDigest(artifact.provider),
    },
    stateIsolation: {
      kind:
        artifact.provider === "terraform"
          ? "terraform-remote-state"
          : "arm-deployment-history",
      identifier: stateIdentifier,
      primaryIdentifier,
      isolated: stateIdentifier !== primaryIdentifier,
    },
    steps,
    resume: deriveResume(steps),
    postchecks: postchecks(),
    teardown: teardownPlan(),
    safety: {
      executionEnabled: false,
      azureOperations: "none",
      providerRegistration: false,
      globalIngress: false,
      workloadFailover: false,
      dataFailover: false,
      productionExecution: false,
    },
  };
  document.manifestDigest = digestDocument(document, "manifestDigest");
  validateDocument(manifestSchema, document);
  validateStepStateSemantics(document);
  const path = resolve(
    outputDirectory,
    `${artifact.provider}-cool-foundation-manifest.json`,
  );
  writeGenerated(path, document);
  return { document, path };
}

function readinessBinding(plan, evaluatedAt) {
  const evidence = plan.readinessEvidence;
  const owner = evidence.humanAttestations.failoverOwner;
  const cost = evidence.humanAttestations.coolFootprintCost;
  const exercise = evidence.humanAttestations.recoveryExercise;
  return {
    evidenceId: evidence.evidenceId,
    evidenceDigest: evidence.evidenceDigest,
    issuedAt: evidence.issuedAt,
    expiresAt: evidence.expiresAt,
    freshness: freshness(evidence, evaluatedAt),
    secondaryRegion: evidence.subject.secondaryRegion,
    billingSupport: attestationBinding(
      evidence.humanAttestations.startupBillingSupport,
    ),
    owner: {
      ...attestationBinding(owner),
      ownerReference: owner.ownerReference,
      roleReference: owner.roleReference,
      roleDisplayName: owner.roleDisplayName ?? null,
    },
    recoveryObjectives: evidence.humanAttestations.recoveryMeasurements.map(
      (item) => ({
        ...attestationBinding(item),
        profileId: item.profileId,
        targetRtoMinutes: item.targetRtoMinutes,
        targetRpoMinutes: item.targetRpoMinutes,
        measuredRtoMinutes: item.measuredRtoMinutes,
        measuredRpoMinutes: item.measuredRpoMinutes,
      }),
    ),
    cost: cost
      ? {
          ...attestationBinding(cost),
          currency: cost.currency,
          minimum: cost.minimum,
          maximum: cost.maximum,
          primaryMonthlyCost: cost.primaryMonthlyCost,
          ceilingPercent: cost.ceilingPercent,
          projectedPercent: cost.projectedPercent,
          provenanceReference: cost.provenanceReference,
        }
      : null,
    externalReviews: Object.values(
      evidence.humanAttestations.externalReviews,
    )
      .map(attestationBinding)
      .sort((left, right) => left.reference.localeCompare(right.reference)),
    recoveryExercise: exercise ? attestationBinding(exercise) : null,
  };
}

function generateCoolFoundationPlan(
  plan,
  baseline,
  {
    outputPath = ".sslz/generated/cool-foundation",
    evaluatedAt = Date.now(),
  } = {},
) {
  validateDocument(summarySchema, plan);
  validateDocument(baselineSchema, baseline);
  if (phaseFourPlanDigest(plan.decisionModel) !== plan.planDigest) {
    throw new Error("The source Phase 4 plan digest does not match its decisions.");
  }
  if (!plan.readinessEvidence) {
    throw new Error("A bound readiness evidence artifact is required.");
  }
  const outputDirectory = generatedPath(outputPath, "Output directory");
  const gates = evaluateGates(plan, baseline, evaluatedAt);
  const artifacts = exactSecondaryArtifacts(plan);
  if (artifacts.length !== 2) {
    throw new Error("Exactly one Bicep and one Terraform secondary artifact are required.");
  }
  const manifests = artifacts.map((artifact) =>
    buildManifest(plan, artifact, outputDirectory),
  );
  const names = resourceNames(plan);
  const subscription = plan.decisionModel.target.environments.find(
    (item) => item.name === "nonprod",
  ).subscriptionId;
  const payload = {
    schemaVersion: PLAN_VERSION,
    plannerVersion: PLAN_VERSION,
    generatedBy: GENERATED_BY,
    planId: `${plan.planId}-cool-foundation`,
    evaluatedAt: new Date(evaluatedAt).toISOString(),
    status: gates.every((item) => item.status === "pass")
      ? "ready-for-review"
      : "blocked",
    mode: "cool-infrastructure",
    environment: "nonprod",
    sourcePlan: {
      schemaVersion: plan.schemaVersion,
      planId: plan.planId,
      planDigest: plan.planDigest,
      approvalStatus: plan.approval.status,
      approvalExpiresAt: plan.approval.expiresAt,
    },
    baseline,
    readinessBinding: readinessBinding(plan, evaluatedAt),
    gateResults: gates,
    foundation: {
      primary: {
        region: plan.decisionModel.regional.primary.region,
        vnetCidr: plan.decisionModel.regional.primary.vnetCidr,
      },
      secondary: {
        region: plan.decisionModel.regional.secondary.region,
        vnetCidr: plan.decisionModel.regional.secondary.vnetCidr,
        subscriptionId: subscription,
        resourceNames: names,
      },
      isolation: {
        addressSpace: "non-overlapping",
        resourceGroups: "secondary-specific",
        terraformState: artifacts.find((item) => item.provider === "terraform")
          .stateKey,
        scope: `/subscriptions/${subscription}/resourceGroups/${names.networkingResourceGroup}`,
      },
      excludedCapabilities: [
        "data-failover",
        "data-replication",
        "global-ingress",
        "production-execution",
        "profile-workload",
        "traffic-failover",
      ],
    },
    manifests: manifests.map(({ document, path }) => ({
      provider: document.provider,
      path: relativePath(path),
      digest: document.manifestDigest,
    })),
    deploymentStateContract: {
      states: [
        "pending",
        "running",
        "succeeded",
        "failed",
        "cleanup-required",
      ],
      ordered: true,
      singleActiveStep: true,
      idempotencyRequired: true,
      resumeRequiresArtifactDigestMatch: true,
      partialFailure: "fail-closed",
    },
    safety: {
      executionEnabled: false,
      azureOperations: "none",
      singleExecutableProductionMode: "single-region-ready",
      secondaryPreview: "not-run",
      providerRegistration: false,
      liveBillingQuery: false,
      humanAttestationsSynthesized: false,
    },
  };
  const planDigest = hashCanonical(payload);
  const document = {
    ...payload,
    planDigest,
    approvalBinding: {
      required: true,
      status: "pending",
      signingDomain: "sslz.cool-foundation.approval.v1",
      planDigest,
      readinessEvidenceDigest: plan.readinessEvidence.evidenceDigest,
      manifestDigests: manifests
        .map(({ document: manifest }) => manifest.manifestDigest)
        .sort(),
      requiredReviewReferences: Object.values(
        plan.readinessEvidence.humanAttestations.externalReviews,
      )
        .map((review) => review.reference)
        .sort(),
      executionApprovalAccepted: false,
    },
  };
  validateDocument(planSchema, document);
  const path = resolve(outputDirectory, "cool-foundation-plan.json");
  writeGenerated(path, document);
  return document;
}

function validateCoolFoundationPlan(document) {
  validateDocument(planSchema, document);
  const payload = structuredClone(document);
  delete payload.planDigest;
  delete payload.approvalBinding;
  if (hashCanonical(payload) !== document.planDigest) {
    throw new Error("The cool foundation plan digest does not match its canonical content.");
  }
  if (document.approvalBinding.planDigest !== document.planDigest) {
    throw new Error("The approval binding does not match the cool foundation plan digest.");
  }
  for (const manifestBinding of document.manifests) {
    const path = resolve(root, manifestBinding.path);
    const manifest = JSON.parse(readFileSync(path, "utf8"));
    validateDocument(manifestSchema, manifest);
    if (
      digestDocument(manifest, "manifestDigest") !== manifest.manifestDigest ||
      manifest.manifestDigest !== manifestBinding.digest
    ) {
      throw new Error(`Manifest digest mismatch: ${manifestBinding.provider}.`);
    }
    validateStepStateSemantics(manifest);
  }
  return document;
}

function usage() {
  return [
    "Usage:",
    "  startup-cool-foundation-plan.mjs generate --plan <phase4-plan.json>",
    "    --baseline <baseline.json> [--output-dir .sslz/generated/<name>]",
    "  startup-cool-foundation-plan.mjs validate --plan <cool-foundation-plan.json>",
    "",
    "This command generates or validates local planning artifacts only.",
    "It has no preview, apply, provider-registration, billing, or Azure operation.",
  ].join("\n");
}

function parseArguments(args) {
  if (args.includes("--help") || args.includes("-h")) {
    return { help: true };
  }
  const command = args[0];
  if (!["generate", "validate"].includes(command)) {
    throw new Error("The supported commands are generate and validate.");
  }
  const options = { command, outputPath: ".sslz/generated/cool-foundation" };
  for (let index = 1; index < args.length; index += 1) {
    const argument = args[index];
    if (argument === "--plan") {
      options.planPath = args[++index];
    } else if (argument === "--baseline") {
      options.baselinePath = args[++index];
    } else if (argument === "--output-dir") {
      options.outputPath = args[++index];
    } else {
      throw new Error(`Unknown argument: ${argument}`);
    }
  }
  if (!options.planPath) {
    throw new Error("--plan is required.");
  }
  if (command === "generate" && !options.baselinePath) {
    throw new Error("--baseline is required for generation.");
  }
  return options;
}

function readJson(path) {
  return JSON.parse(readFileSync(resolve(process.cwd(), path), "utf8"));
}

function main() {
  try {
    const options = parseArguments(process.argv.slice(2));
    if (options.help) {
      process.stdout.write(`${usage()}\n`);
      return;
    }
    const result =
      options.command === "generate"
        ? generateCoolFoundationPlan(
            readJson(options.planPath),
            readJson(options.baselinePath),
            { outputPath: options.outputPath },
          )
        : validateCoolFoundationPlan(readJson(options.planPath));
    process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
    process.exitCode = result.status === "blocked" ? 1 : 0;
  } catch (error) {
    process.stderr.write(`Cool foundation planning failed: ${error.message}\n`);
    process.exitCode = 2;
  }
}

