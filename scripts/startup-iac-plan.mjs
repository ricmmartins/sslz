function terraformName(name) {
  return name.replace(/[A-Z]/g, (letter) => `_${letter.toLowerCase()}`);
}

function renderTerraformVariables(values, previewEligible) {
  return [
    `# ${GENERATED_MARKER}. Review before preview.`,
    ...(previewEligible
      ? []
      : [
          "# Secondary foundation representation only; execution is disabled in Phase 7.",
        ]),
    ...Object.entries(values).map(
      ([name, value]) => `${terraformName(name)} = ${JSON.stringify(value)}`,
    ),
    "",
  ].join("\n");
}

function artifactDefinitions(
  decisionModel,
  providers,
  outputDirectory,
  notificationContacts,
) {
  const regionalTargets = [
    { role: "primary", ...decisionModel.regional.primary },
    ...(decisionModel.regional.secondary
      ? [{ role: "secondary", ...decisionModel.regional.secondary }]
      : []),
  ];
  return providers.flatMap((provider) =>
    decisionModel.target.environments.flatMap((environment) =>
      regionalTargets
        .filter(
          (regionalTarget) =>
            regionalTarget.role === "primary" || environment.name === "nonprod",
        )
        .map((regionalTarget) => {
        const extension =
          provider === "bicep" ? "local.bicepparam" : "auto.tfvars";
        const path = resolve(
          outputDirectory,
          provider,
          `${environment.name}-${regionalTarget.role}.${extension}`,
        );
        const sourcePath =
          regionalTarget.role === "secondary"
            ? provider === "bicep"
              ? "infra/bicep/cool-foundation.bicep"
              : "infra/terraform/cool-foundation"
            : provider === "bicep"
              ? "infra/bicep/main.bicep"
              : "infra/terraform";
        return {
          provider,
          environment,
          regionalTarget,
          path,
          sourcePath,
          previewEligible: regionalTarget.role === "primary",
          values: parameterValues(
            decisionModel,
            environment,
            regionalTarget,
            notificationContacts,
          ),
        };
        }),
    ),
  );
}

function writeParameterArtifacts(definitions) {
  for (const definition of definitions) {
    const content =
      definition.provider === "bicep"
        ? renderBicepParameters(
            definition.values,
            definition.path,
            definition.previewEligible,
            definition.sourcePath,
          )
        : renderTerraformVariables({
            subscriptionId: definition.environment.subscriptionId,
            resourceProviderRegistrations: "none",
            resourceProvidersToRegister: [],
            ...definition.values,
          }, definition.previewEligible);
    writeGeneratedFile(definition.path, content);
  }
}

function reconcileParameterArtifacts(definitions, outputDirectory) {
  const expected = new Set(definitions.map((definition) => definition.path));
  for (const provider of SUPPORTED_PROVIDERS) {
    const providerDirectory = resolve(outputDirectory, provider);
    if (!existsSync(providerDirectory)) {
      continue;
    }
    assertNoLinkedComponents(providerDirectory);
    for (const name of readdirSync(providerDirectory)) {
      if (
        !name.endsWith(".local.bicepparam") &&
        !name.endsWith(".auto.tfvars")
      ) {
        continue;
      }
      const path = resolve(providerDirectory, name);
      if (expected.has(path)) {
        continue;
      }
      const content = readFileSync(path, "utf8");
      if (!content.includes(GENERATED_MARKER)) {
        throw new Error(
          `Refusing to remove a non-generated parameter file: ${relativePath(path)}.`,
        );
      }
      unlinkSync(path);
    }
  }
}

function parseChangeCount(text, patterns) {
  for (const pattern of patterns) {
    const match = text.match(pattern);
    if (match) {
      return Number(match[1]);
    }
  }
  return 0;
}

function classifyPreviewError(text) {
  if (/auth|login|credential|unauthorized|forbidden|permission/i.test(text)) {
    return {
      errorClass: "authentication",
      message: "Preview failed because authentication or authorization was unavailable.",
    };
  }
  if (/backend|state/i.test(text)) {
    return {
      errorClass: "backend",
      message: "Preview failed while accessing the configured remote state backend.",
    };
  }
  if (/configuration|invalid|validation|parse|syntax/i.test(text)) {
    return {
      errorClass: "configuration",
      message: "Preview failed because the generated input or IaC configuration was invalid.",
    };
  }
  if (/provider|plugin/i.test(text)) {
    return {
      errorClass: "provider",
      message: "Preview failed while initializing or using the IaC provider.",
    };
  }
  return {
    errorClass: "unknown",
    message: "Preview failed; raw tool output was not retained.",
  };
}

function summarizePreview(provider, execution) {
  const output = `${execution.stdout ?? ""}\n${execution.stderr ?? ""}`;
  const noChanges = /no changes|no change/i.test(output);
  const terraformSummary =
    provider === "terraform"
      ? output.match(
          /Plan:\s*(?:(\d+)\s+to import,\s*)?(\d+)\s+to add,\s*(\d+)\s+to change,\s*(\d+)\s+to destroy/i,
        )
      : null;
  const create =
    provider === "terraform"
      ? Number(terraformSummary?.[2] ?? 0)
      : parseChangeCount(output, [/Create:\s*(\d+)/i, /(\d+)\s+to create/i]);
  const modify =
    provider === "terraform"
      ? Number(terraformSummary?.[3] ?? 0)
      : parseChangeCount(output, [/Modify:\s*(\d+)/i, /(\d+)\s+to modify/i]);
  const remove =
    provider === "terraform"
      ? Number(terraformSummary?.[4] ?? 0)
      : parseChangeCount(output, [/Delete:\s*(\d+)/i, /(\d+)\s+to delete/i]);
  const classified =
    noChanges ||
    (provider === "terraform"
      ? terraformSummary !== null
      : /(?:Create|Modify|Delete):\s*\d+|\d+\s+to (?:create|modify|delete)/i.test(
          output,
        ));

  if (execution.status !== 0) {
    const classified = classifyPreviewError(output);
    return {
      status: "failed",
      changes: { create: 0, modify: 0, remove: 0 },
      destructiveChanges: false,
      errorClass: classified.errorClass,
      message: classified.message,
    };
  }
  if (!classified) {
    return {
      status: "failed",
      changes: { create: 0, modify: 0, remove: 0 },
      destructiveChanges: false,
      errorClass: "unknown",
      message: "Preview completed but its change summary could not be classified safely.",
    };
  }

  return {
    status: remove > 0 ? "blocked" : "succeeded",
    changes: {
      create: noChanges ? 0 : create,
      modify: noChanges ? 0 : modify,
      remove: noChanges ? 0 : remove,
    },
    destructiveChanges: remove > 0,
    errorClass: null,
    message:
      remove > 0
        ? "Preview contains destructive changes and is blocked for review."
        : noChanges
          ? "Preview completed with no changes."
          : "Preview completed; only sanitized change counts were retained.",
  };
}

function sanitizedTerraformEnvironment(
  extra,
  cliConfigPath,
  authMode = null,
) {
  const environment = {};
  const allowed = [
    "ALL_PROXY",
    "ARM_CLIENT_ID",
    "ARM_TENANT_ID",
    "ARM_USE_AZUREAD",
    "HTTPS_PROXY",
    "HTTP_PROXY",
    "NO_PROXY",
    "PATH",
    "SYSTEMROOT",
  ];
  if (authMode === "oidc") {
    allowed.push(
      "ACTIONS_ID_TOKEN_REQUEST_TOKEN",
      "ACTIONS_ID_TOKEN_REQUEST_URL",
      "ARM_OIDC_REQUEST_TOKEN",
      "ARM_OIDC_REQUEST_URL",
    );
  }
  const sourceKeys = new Map(
    Object.keys(process.env).map((key) => [key.toUpperCase(), key]),
  );
  for (const key of allowed) {
    const sourceKey = sourceKeys.get(key);
    if (sourceKey && process.env[sourceKey] !== undefined) {
      environment[key] = process.env[sourceKey];
    }
  }
  if (authMode === "cli") {
    environment.ARM_USE_CLI = "true";
    environment.ARM_USE_OIDC = "false";
    environment.AZURE_CONFIG_DIR = azureCliConfigDirectory();
  } else if (authMode === "oidc") {
    environment.ARM_USE_CLI = "false";
    environment.ARM_USE_OIDC = "true";
  }
  return {
    ...environment,
    ...extra,
    ...(extra.TF_DATA_DIR
      ? {
          TEMP: extra.TF_DATA_DIR,
          TMP: extra.TF_DATA_DIR,
          TMPDIR: extra.TF_DATA_DIR,
        }
      : {}),
    TF_IN_AUTOMATION: "1",
    TF_INPUT: "0",
    TF_CLI_CONFIG_FILE: cliConfigPath,
  };
}

function runCommand(
  command,
  args,
  cwd,
  environment = {},
  terraformCliConfigPath = null,
  terraformAuthMode = null,
  terraformExecutablePath = null,
) {
  let invocation;
  try {
    invocation =
      command === "az"
        ? azureCliInvocation(args)
        : command === "terraform"
          ? {
              executable:
                terraformExecutablePath ?? terraformExecutable().path,
              arguments: args,
            }
          : { executable: command, arguments: args };
  } catch {
    return {
      status: null,
      stdout: "",
      stderr: "Azure CLI is unavailable.",
    };
  }
  return spawnSync(invocation.executable, invocation.arguments, {
    cwd,
    encoding: "utf8",
    env:
      command === "terraform"
        ? sanitizedTerraformEnvironment(
            environment,
            terraformCliConfigPath ??
              resolve(root, "infra/terraform/sslz.deployment.tfrc"),
            terraformAuthMode,
          )
        : command === "az"
          ? sanitizedAzureCliEnvironment(environment)
          : { ...process.env, ...environment },
    maxBuffer: 16 * 1024 * 1024,
    shell: false,
    windowsHide: true,
  });
}

function terraformSourceFiles() {
  const directory = resolve(root, "infra/terraform");
  const files = [];
  function visit(path) {
    for (const entry of readdirSync(path, { withFileTypes: true }).sort(
      (left, right) => left.name.localeCompare(right.name),
    )) {
      const child = resolve(path, entry.name);
      if (entry.isSymbolicLink()) {
        throw new Error("Terraform provenance source cannot contain symbolic links.");
      }
      if (entry.isDirectory()) {
        if (entry.name !== ".terraform") {
          visit(child);
        }
      } else if (
        entry.isFile() &&
        (child.endsWith(".tf") ||
          child.endsWith(".terraform.lock.hcl") ||
          child.endsWith("sslz.deployment.tfrc"))
      ) {
        files.push(child);
      }
    }
  }
  visit(directory);
  return files.sort((left, right) =>
    relativePath(left).localeCompare(relativePath(right)),
  );
}

function readRegularFile(path) {
  let descriptor;
  try {
    descriptor = openSync(path, constants.O_RDONLY | constants.O_NOFOLLOW);
    if (!fstatSync(descriptor).isFile()) {
      throw new Error("Terraform provenance inputs must be regular files.");
    }
    return readFileSync(descriptor);
  } finally {
    if (descriptor !== undefined) {
      closeSync(descriptor);
    }
  }
}

function writeSnapshotFile(snapshotRoot, sourcePath) {
  const content = readRegularFile(sourcePath);
  const destination = resolve(snapshotRoot, relative(root, sourcePath));
  mkdirSync(dirname(destination), { recursive: true, mode: 0o700 });
  writeFileSync(destination, content, { flag: "wx", mode: 0o600 });
  return {
    path: destination,
    logicalPath: relativePath(sourcePath),
    digest: hashBytes(content),
  };
}

function setSnapshotMode(path, directoryMode, fileMode) {
  for (const entry of readdirSync(path, { withFileTypes: true })) {
    const child = resolve(path, entry.name);
    if (entry.isDirectory()) {
      setSnapshotMode(child, directoryMode, fileMode);
    } else if (entry.isFile()) {
      chmodSync(child, fileMode);
    }
  }
  chmodSync(path, directoryMode);
}

function createTerraformBuildSnapshot(parameterPath) {
  const snapshotRoot = mkdtempSync(
    resolve(tmpdir(), "sslz-terraform-build-"),
  );
  chmodSync(snapshotRoot, 0o700);
  try {
    const sourceEntries = terraformSourceFiles().map((path) =>
      writeSnapshotFile(snapshotRoot, path),
    );
    const parameter = writeSnapshotFile(snapshotRoot, parameterPath);
    return {
      root: snapshotRoot,
      terraformDirectory: resolve(snapshotRoot, "infra/terraform"),
      terraformCliConfigPath: resolve(
        snapshotRoot,
        "infra/terraform/sslz.deployment.tfrc",
      ),
      sourceDigest: hashCanonical(
        sourceEntries.map(({ logicalPath: path, digest }) => ({
          path,
          digest,
        })),
      ),
      providerLockDigest: sourceEntries.find(({ logicalPath }) =>
        logicalPath.endsWith(".terraform.lock.hcl"),
      ).digest,
      parameter,
    };
  } catch (error) {
    setSnapshotMode(snapshotRoot, 0o700, 0o600);
    rmSync(snapshotRoot, { recursive: true, force: true });
    throw error;
  }
}

function readProvenancePrivateKey() {
  const requestedPath =
    process.env.SSLZ_TERRAFORM_PROVENANCE_PRIVATE_KEY_FILE;
  if (!requestedPath || !isAbsolute(requestedPath)) {
    throw new Error(
      "Terraform raw plan generation requires SSLZ_TERRAFORM_PROVENANCE_PRIVATE_KEY_FILE.",
    );
  }
  const path = resolve(requestedPath);
  let current = path;
  const filesystemRoot = parse(path).root;
  while (current !== filesystemRoot) {
    if (existsSync(current) && lstatSync(current).isSymbolicLink()) {
      throw new Error("The Terraform provenance signing-key path cannot contain symbolic links.");
    }
    current = dirname(current);
  }
  return readFileSync(path);
}

function persistTerraformProvenance(
  decisionModel,
  definition,
  buildSnapshot,
  savedPlanPath,
  planDocument,
  useOidc,
  terraformIdentity,
  terraformExecutableDigest,
) {
  const savedPlan = readRegularFile(savedPlanPath);
  const payload = {
    sourceDigest: buildSnapshot.sourceDigest,
    parameterDigest: buildSnapshot.parameter.digest,
    backendDigest: hashCanonical({
      backend: decisionModel.terraformBackend,
      arguments: terraformBackendArguments(
        decisionModel,
        definition,
        useOidc,
      ),
    }),
    providerLockDigest: buildSnapshot.providerLockDigest,
    savedPlanDigest: hashBytes(savedPlan),
    planJsonDigest: hashCanonical(planDocument),
    configurationDigest: hashCanonical(planDocument.configuration),
    plannedValuesDigest: hashCanonical(planDocument.planned_values),
    providerConfigurationDigest: hashCanonical(
      planDocument.configuration.provider_config,
    ),
    resourceChangesDigest: hashCanonical(planDocument.resource_changes),
    variablesDigest: hashCanonical(planDocument.variables),
    terraformVersion: terraformIdentity.terraform_version,
    terraformPlatform: terraformIdentity.platform,
    terraformExecutableDigest,
  };
  return {
    savedPlan,
    provenance: signTerraformProvenance(
      payload,
      readProvenancePrivateKey(),
    ),
  };
}

function terraformBackendArguments(decisionModel, definition, useOidc) {
  const backend = decisionModel.terraformBackend;
  return [
    ...(backend.subscriptionId
      ? [`-backend-config=subscription_id=${backend.subscriptionId}`]
      : []),
    `-backend-config=resource_group_name=${backend.resourceGroupName}`,
    `-backend-config=storage_account_name=${backend.storageAccountName}`,
    `-backend-config=container_name=${backend.containerName}`,
    `-backend-config=key=${backend.keyPrefix}-${definition.environment.name}-${definition.regionalTarget.role}.tfstate`,
    `-backend-config=use_oidc=${useOidc}`,
    `-backend-config=use_cli=${!useOidc}`,
    "-backend-config=use_azuread_auth=true",
  ];
}

function assertArtifactDestinationsAvailable(paths) {
  if (paths.some((path) => path && existsSync(path))) {
    throw new Error("Refusing to overwrite an existing raw artifact.");
  }
}

function rawOutputPath(definition, rawArtifactDirectory, suffix) {
  return rawArtifactDirectory
    ? resolve(
        rawArtifactDirectory,
        `${definition.provider}-${definition.environment.name}-${definition.regionalTarget.role}-${suffix}`,
      )
    : null;
}

function writeExclusiveArtifacts(entries) {
  assertArtifactDestinationsAvailable(entries.map(({ path }) => path));
  const created = [];
  try {
    for (const { path, content } of entries) {
      const descriptor = openSync(path, "wx", 0o600);
      created.push(path);
      try {
        writeFileSync(descriptor, content, { encoding: "utf8" });
      } finally {
        closeSync(descriptor);
      }
    }
  } catch (error) {
    for (const path of created.reverse()) {
      unlinkSync(path);
    }
    throw error;
  }
}

function executePreview(decisionModel, definition, rawArtifactDirectory) {
  if (definition.provider === "bicep") {
    assertArtifactDestinationsAvailable([
      rawOutputPath(definition, rawArtifactDirectory, "what-if.txt"),
    ]);
    const result = runCommand(
      "az",
      [
        "deployment",
        "sub",
        "what-if",
        "--subscription",
        definition.environment.subscriptionId,
        "--location",
        definition.regionalTarget.region,
        "--template-file",
        resolve(root, "infra/bicep/main.bicep"),
        "--parameters",
        definition.path,
        "--name",
        `sslz-preview-${definition.environment.name}-${definition.regionalTarget.role}`,
        "--result-format",
        "ResourceIdOnly",
      ],
      root,
    );
    return {
      ...persistRawOutput(
        result,
        definition,
        rawArtifactDirectory,
        "what-if.txt",
      ),
      provenanceArtifact: null,
      planJsonArtifact: null,
    };
  }

  const useOidc = process.env.GITHUB_ACTIONS === "true";
  const trustedTerraform = terraformExecutable();
  const rawPlanPath = rawArtifactDirectory
    ? resolve(
        rawArtifactDirectory,
        `${definition.environment.name}-${definition.regionalTarget.role}.tfplan`,
      )
    : null;
  const planJsonPath = rawPlanPath
    ? resolve(
        rawArtifactDirectory,
        `${definition.environment.name}-${definition.regionalTarget.role}.plan.json`,
      )
    : null;
  const provenancePath = rawPlanPath
    ? resolve(
        rawArtifactDirectory,
        `${definition.environment.name}-${definition.regionalTarget.role}.provenance.json`,
      )
    : null;
  const versionOutputPath = rawOutputPath(
    definition,
    rawArtifactDirectory,
    "version.txt",
  );
  const initOutputPath = rawOutputPath(
    definition,
    rawArtifactDirectory,
    "init.txt",
  );
  const showOutputPath = rawOutputPath(
    definition,
    rawArtifactDirectory,
    "show.txt",
  );
  const planOutputPath = rawOutputPath(
    definition,
    rawArtifactDirectory,
    "plan.txt",
  );
  assertArtifactDestinationsAvailable([
    rawPlanPath,
    planJsonPath,
    provenancePath,
    versionOutputPath,
    initOutputPath,
    showOutputPath,
    planOutputPath,
  ]);
  const snapshot = createTerraformBuildSnapshot(definition.path);
  try {
    const snapshotTerraformPath = resolve(
      snapshot.root,
      process.platform === "win32" ? "terraform.exe" : "terraform",
    );
    const terraformBytes = readFileSync(trustedTerraform.path);
    if (hashBytes(terraformBytes) !== trustedTerraform.digest) {
      throw new Error("The trusted Terraform executable changed during snapshot.");
    }
    writeFileSync(snapshotTerraformPath, terraformBytes, {
      flag: "wx",
      mode: 0o500,
    });
    const terraformDataDirectory = resolve(snapshot.root, "terraform-data");
    mkdirSync(terraformDataDirectory, { mode: 0o700 });
    const environment = { TF_DATA_DIR: terraformDataDirectory };
    const identityExecution = runCommand(
      "terraform",
      ["version", "-json"],
      snapshot.root,
      environment,
      snapshot.terraformCliConfigPath,
      useOidc ? "oidc" : "cli",
      snapshotTerraformPath,
    );
    let terraformIdentity = null;
    try {
      terraformIdentity = JSON.parse(identityExecution.stdout);
    } catch {
      terraformIdentity = null;
    }
    if (
      identityExecution.status !== 0 ||
      !/^[0-9]+\.[0-9]+\.[0-9]+(?:[-+][A-Za-z0-9.-]+)?$/.test(
        terraformIdentity?.terraform_version ?? "",
      ) ||
      !/^(?:windows|linux|darwin)_(?:amd64|arm64|386)$/.test(
        terraformIdentity?.platform ?? "",
      )
    ) {
      return {
        ...persistRawOutput(
          {
            status: 1,
            stdout: "",
            stderr: "Terraform executable identity could not be verified.",
          },
          definition,
          rawArtifactDirectory,
          "version.txt",
        ),
        provenanceArtifact: null,
        planJsonArtifact: null,
      };
    }
    const init = runCommand(
      "terraform",
      [
        `-chdir=${snapshot.terraformDirectory}`,
        "init",
        "-input=false",
        "-reconfigure",
        "-lockfile=readonly",
        ...terraformBackendArguments(decisionModel, definition, useOidc),
      ],
      snapshot.root,
      environment,
      snapshot.terraformCliConfigPath,
      useOidc ? "oidc" : "cli",
      snapshotTerraformPath,
    );
    if (init.status !== 0) {
      return {
        ...persistRawOutput(
          init,
          definition,
          rawArtifactDirectory,
          "init.txt",
        ),
        provenanceArtifact: null,
        planJsonArtifact: null,
      };
    }
    const snapshotPlanPath = rawPlanPath
      ? resolve(snapshot.root, "reviewed.tfplan")
      : null;
    const result = runCommand(
      "terraform",
      [
        `-chdir=${snapshot.terraformDirectory}`,
        "plan",
        "-input=false",
        "-no-color",
        `-var-file=${snapshot.parameter.path}`,
        ...(snapshotPlanPath ? [`-out=${snapshotPlanPath}`] : []),
      ],
      snapshot.root,
      environment,
      snapshot.terraformCliConfigPath,
      useOidc ? "oidc" : "cli",
      snapshotTerraformPath,
    );
    let provenanceArtifact = null;
    let planJsonArtifact = null;
    if (result.status === 0 && snapshotPlanPath) {
      const shown = runCommand(
        "terraform",
        [
          `-chdir=${snapshot.terraformDirectory}`,
          "show",
          "-json",
          snapshotPlanPath,
        ],
        snapshot.root,
        environment,
        snapshot.terraformCliConfigPath,
        useOidc ? "oidc" : "cli",
        snapshotTerraformPath,
      );
      if (shown.status !== 0) {
        return {
          ...persistRawOutput(
            shown,
            definition,
            rawArtifactDirectory,
            "show.txt",
          ),
          provenanceArtifact: null,
          planJsonArtifact: null,
        };
      }
      const planDocument = JSON.parse(shown.stdout);
      if (planDocument.terraform_version !== terraformIdentity.terraform_version) {
        return {
          ...persistRawOutput(
            {
              status: 1,
              stdout: "",
              stderr:
                "The saved plan version does not match the Terraform executable.",
            },
            definition,
            rawArtifactDirectory,
            "show.txt",
          ),
          provenanceArtifact: null,
          planJsonArtifact: null,
        };
      }
      const { savedPlan, provenance } = persistTerraformProvenance(
        decisionModel,
        definition,
        snapshot,
        snapshotPlanPath,
        planDocument,
        useOidc,
        terraformIdentity,
        trustedTerraform.digest,
      );
      mkdirSync(rawArtifactDirectory, { recursive: true });
      writeExclusiveArtifacts([
        { path: rawPlanPath, content: savedPlan },
        {
          path: planJsonPath,
          content: `${JSON.stringify(planDocument, null, 2)}\n`,
        },
        {
          path: provenancePath,
          content: `${JSON.stringify(provenance, null, 2)}\n`,
        },
        {
          path: planOutputPath,
          content: `${result.stdout ?? ""}${result.stderr ?? ""}`,
        },
      ]);
      provenanceArtifact = relativePath(provenancePath);
      planJsonArtifact = relativePath(planJsonPath);
      return {
        execution: result,
        rawArtifact: relativePath(planOutputPath),
        provenanceArtifact,
        planJsonArtifact,
      };
    }
    return {
      ...persistRawOutput(
        result,
        definition,
        rawArtifactDirectory,
        "plan.txt",
      ),
      provenanceArtifact,
      planJsonArtifact,
    };
  } finally {
    setSnapshotMode(snapshot.root, 0o700, 0o600);
    rmSync(snapshot.root, { recursive: true, force: true });
  }
}

function persistRawOutput(execution, definition, rawArtifactDirectory, suffix) {
  if (!rawArtifactDirectory) {
    return { execution, rawArtifact: null };
  }
  mkdirSync(rawArtifactDirectory, { recursive: true });
  const rawPath = rawOutputPath(definition, rawArtifactDirectory, suffix);
  writeExclusiveArtifacts([
    {
      path: rawPath,
      content: `${execution.stdout ?? ""}${execution.stderr ?? ""}`,
    },
  ]);
  return { execution, rawArtifact: relativePath(rawPath) };
}

function previewDefinitions(
  decisionModel,
  definitions,
  { execute, fixtures, rawArtifactDirectory },
) {
  if (!execute && !fixtures) {
    return definitions.map((definition) => ({
      provider: definition.provider,
      environment: definition.environment.name,
      regionRole: definition.regionalTarget.role,
      region: definition.regionalTarget.region,
      source: "none",
      status: definition.previewEligible ? "not-run" : "representation-only",
      changes: { create: 0, modify: 0, remove: 0 },
      destructiveChanges: false,
      errorClass: null,
      message: definition.previewEligible
        ? "Preview was not requested."
        : "Secondary parameters are review-only because the current SSLZ roots are single-region.",
      rawArtifact: null,
      provenanceArtifact: null,
      planJsonArtifact: null,
    }));
  }

  return definitions.map((definition) => {
    if (!definition.previewEligible) {
      return {
        provider: definition.provider,
        environment: definition.environment.name,
        regionRole: definition.regionalTarget.role,
        region: definition.regionalTarget.region,
        source: "none",
        status: "representation-only",
        changes: { create: 0, modify: 0, remove: 0 },
        destructiveChanges: false,
        errorClass: null,
        message:
          "Secondary parameters are review-only because the current SSLZ roots are single-region.",
        rawArtifact: null,
        provenanceArtifact: null,
        planJsonArtifact: null,
      };
    }
    const fixture = fixtures?.[definition.provider];
    const result = fixture
      ? {
          execution: {
            status: fixture.exitCode,
            stdout: fixture.stdout ?? "",
            stderr: fixture.stderr ?? "",
          },
          rawArtifact: null,
          provenanceArtifact: null,
          planJsonArtifact: null,
        }
      : executePreview(decisionModel, definition, rawArtifactDirectory);
    return {
      provider: definition.provider,
      environment: definition.environment.name,
      regionRole: definition.regionalTarget.role,
      region: definition.regionalTarget.region,
      source: fixture ? "fixture" : "command",
      ...summarizePreview(definition.provider, result.execution),
      rawArtifact: result.rawArtifact,
      provenanceArtifact: result.provenanceArtifact ?? null,
      planJsonArtifact: result.planJsonArtifact ?? null,
    };
  });
}

function normalizeProviders(providers) {
  const normalized = [...new Set(providers)].sort();
  if (
    normalized.length === 0 ||
    normalized.some((provider) => !SUPPORTED_PROVIDERS.has(provider))
  ) {
    throw new Error("Provider must be bicep, terraform, or both.");
  }
  return normalized;
}

function generateIacPlan(
  input,
  {
    providers = ["bicep", "terraform"],
    outputPath = ".sslz/generated",
    executePreviewCommands = false,
    previewFixtures = null,
    rawArtifactPath = null,
    notificationContacts = null,
    evaluatedAt = Date.now(),
  } = {},
) {
  validateDocument(
    input?.schemaVersion === "3.0.0"
      ? inputSchemaV3
      : input?.schemaVersion === "2.0.0"
        ? inputSchemaV2
        : inputSchema,
    input,
  );
  assertSafeInput(input);
  assertSemanticInput(input, evaluatedAt);

  const selectedProviders = normalizeProviders(providers);
  const outputDirectory = ensureGeneratedPath(outputPath, "Output directory");
  const rawArtifactDirectory = rawArtifactPath
    ? ensureGeneratedPath(rawArtifactPath, "Raw artifact directory")
    : null;
  if (
    rawArtifactDirectory &&
    relative(outputDirectory, rawArtifactDirectory).startsWith("..")
  ) {
    throw new Error("Raw artifact directory must be inside the selected output directory.");
  }

  const decisionModel = buildDecisionModel(input);
  const resolvedNotificationContacts =
    validatedNotificationContacts(notificationContacts);
  const digest = planDigest(decisionModel);
  const definitions = artifactDefinitions(
    decisionModel,
    selectedProviders,
    outputDirectory,
    resolvedNotificationContacts,
  );
  reconcileParameterArtifacts(definitions, outputDirectory);
  writeParameterArtifacts(definitions);
  const previews = previewDefinitions(decisionModel, definitions, {
    execute: executePreviewCommands,
    fixtures: previewFixtures,
    rawArtifactDirectory,
  });
  const result = {
    schemaVersion: SCHEMA_VERSION,
    plannerVersion: PLANNER_VERSION,
    inputContractVersion: input.schemaVersion,
    generatedBy: "startup-iac-plan.mjs",
    planId: input.planId,
    planDigest: digest,
    decisionModel,
    readinessEvidence: input.readinessEvidence ?? null,
    approval: approvalFor(
      input.approval,
      input.planId,
      digest,
      evaluatedAt,
      input.readinessEvidence ?? null,
    ),
    artifacts: definitions.map((definition) => ({
      provider: definition.provider,
      environment: definition.environment.name,
      regionRole: definition.regionalTarget.role,
      region: definition.regionalTarget.region,
      path: relativePath(definition.path),
      digest: hashBytes(readFileSync(definition.path)),
      decisionDigest: hashCanonical(definition.values),
      sourcePath: definition.sourcePath,
      stateKey:
        definition.provider === "terraform"
          ? `${decisionModel.terraformBackend.keyPrefix}-${definition.environment.name}-${definition.regionalTarget.role}.tfstate`
          : null,
      previewEligible: definition.previewEligible,
    })),
    previews,
    safety: {
      azureOperations: executePreviewCommands ? "read-only-preview" : "none",
      bicepDeploymentMode: "incremental-only",
      terraformBackend: "remote-required",
      contactValues: "sanitized-placeholders",
      rawArtifacts: rawArtifactDirectory ? "explicit-local-path" : "not-retained",
    },
  };
  const summaryPath = resolve(outputDirectory, "plan-summary.json");
  writeGeneratedFile(summaryPath, `${JSON.stringify(result, null, 2)}\n`);
  return result;
}

function usage() {
  return [
    "Usage:",
    "  startup-iac-plan.mjs generate --input <path|-> [--provider bicep|terraform|both]",
    "    [--output-dir .sslz/generated/<name>] [--preview]",
    "    [--raw-artifact-dir .sslz/generated/<name>/raw]",
    "    [--notification-contacts-file <absolute-protected-json-path>]",
    "",
    "The command writes ignored local parameters and sanitized summaries only.",
    "It can run read-only what-if/plan previews; it has no write-capable command.",
    "Retained Terraform plans require SSLZ_TERRAFORM_PROVENANCE_PRIVATE_KEY_FILE.",
    "Phase 6-ready artifacts require a protected notification contacts file.",
  ].join("\n");
}

function parseArguments(args) {
  if (args.includes("--help") || args.includes("-h")) {
    return { help: true };
  }
  if (args[0] !== "generate") {
    throw new Error("The only supported command is generate.");
  }

  const options = {
    provider: "both",
    outputPath: ".sslz/generated",
    preview: false,
    rawArtifactPath: null,
    notificationContactsPath: null,
  };
  for (let index = 1; index < args.length; index += 1) {
    const argument = args[index];
    if (argument === "--input") {
      options.inputPath = args[++index];
    } else if (argument === "--provider") {
      options.provider = args[++index];
    } else if (argument === "--output-dir") {
      options.outputPath = args[++index];
    } else if (argument === "--preview") {
      options.preview = true;
    } else if (argument === "--raw-artifact-dir") {
      options.rawArtifactPath = args[++index];
    } else if (argument === "--notification-contacts-file") {
      options.notificationContactsPath = args[++index];
    } else {
      throw new Error(`Unknown argument: ${argument}`);
    }
  }
  if (!options.inputPath) {
    throw new Error("--input is required.");
  }
  if (!["bicep", "terraform", "both"].includes(options.provider)) {
    throw new Error("--provider must be bicep, terraform, or both.");
  }
  if (options.rawArtifactPath && !options.preview) {
    throw new Error("--raw-artifact-dir requires --preview.");
  }
  if (options.rawArtifactPath && !options.notificationContactsPath) {
    throw new Error(
      "--raw-artifact-dir requires --notification-contacts-file for deployable alerting.",
    );
  }
  return { help: false, ...options };
}

function main() {
  try {
    const options = parseArguments(process.argv.slice(2));
    if (options.help) {
      process.stdout.write(`${usage()}\n`);
      return;
    }
    const source =
      options.inputPath === "-"
        ? readFileSync(0, "utf8")
        : readFileSync(resolve(process.cwd(), options.inputPath), "utf8");
    const providers =
      options.provider === "both"
        ? ["bicep", "terraform"]
        : [options.provider];
    const result = generateIacPlan(JSON.parse(source), {
      providers,
      outputPath: options.outputPath,
      executePreviewCommands: options.preview,
      rawArtifactPath: options.rawArtifactPath,
      notificationContacts: options.notificationContactsPath
        ? readNotificationContacts(options.notificationContactsPath)
        : null,
    });
    process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
    process.exitCode = result.previews.some((preview) =>
      ["failed", "blocked"].includes(preview.status),
    )
      ? 1
      : 0;
  } catch (error) {
    process.stderr.write(`IaC planning failed: ${error.message}\n`);
    process.exitCode = 2;
  }
}

