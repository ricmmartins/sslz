class ReadinessEvidenceError extends Error {
  constructor(code, message, checkId) {
    super(message);
    this.code = code;
    this.checkId = checkId ?? READINESS_ERROR_CHECK_IDS.get(code) ?? code;
  }
}

function canonicalJson(value) {
  if (Array.isArray(value)) {
    return `[${value.map((item) => canonicalJson(item)).join(",")}]`;
  }
  if (value && typeof value === "object") {
    return `{${Object.keys(value)
      .sort()
      .map((key) => `${JSON.stringify(key)}:${canonicalJson(value[key])}`)
      .join(",")}}`;
  }
  return JSON.stringify(value);
}

function compareCanonical(left, right) {
  const leftCanonical = canonicalJson(left);
  const rightCanonical = canonicalJson(right);
  return leftCanonical < rightCanonical
    ? -1
    : leftCanonical > rightCanonical
      ? 1
      : 0;
}

function planDigest(decisionModel) {
  return `sha256:${createHash("sha256")
    .update(canonicalJson(decisionModel))
    .digest("hex")}`;
}

function readinessEvidencePayload(evidence) {
  const { evidenceDigest: omitted, ...payload } = evidence;
  return payload;
}

function readinessEvidenceDigest(evidence) {
  return `sha256:${createHash("sha256")
    .update(canonicalJson(readinessEvidencePayload(evidence)))
    .digest("hex")}`;
}

function readinessFail(code, message, checkId) {
  throw new ReadinessEvidenceError(code, message, checkId);
}

function assertEvidenceCurrent(
  item,
  evaluatedAt,
  label,
  timestampField,
  checkId = READINESS_CHECK_IDS.preflight,
) {
  const observedAt = Date.parse(item[timestampField]);
  const expiresAt = Date.parse(item.expiresAt);
  if (
    !Number.isFinite(observedAt) ||
    !Number.isFinite(expiresAt) ||
    observedAt > evaluatedAt ||
    expiresAt <= evaluatedAt ||
    expiresAt <= observedAt
  ) {
    readinessFail(
      "readiness.evidence.stale",
      `${label} is future-dated, stale, expired, or has an invalid freshness window.`,
      checkId,
    );
  }
}

function assertExactEvidenceSet(items, expectedKeys, keyFor, code, label) {
  const actual = items.map(keyFor);
  if (
    actual.length !== new Set(actual).size ||
    canonicalJson([...actual].sort()) !== canonicalJson([...expectedKeys].sort())
  ) {
    readinessFail(code, `${label} does not exactly cover the selected readiness scope.`);
  }
}

function assertReadinessEvidence(input, evaluatedAt = Date.now()) {
  const evidence = input.readinessEvidence;
  if (!evidence) {
    readinessFail(
      "readiness.evidence.required",
      "IaC approval requires a versioned readiness evidence artifact.",
    );
  }
  validateDocument(readinessEvidenceSchema, evidence);
  assertSafeInput(evidence, "$.readinessEvidence");
  if (evidence.status !== "ready") {
    readinessFail(
      "readiness.evidence.blocked",
      "The readiness evidence artifact is not in ready status.",
    );
  }
  if (readinessEvidenceDigest(evidence) !== evidence.evidenceDigest) {
    readinessFail(
      "readiness.evidence.digest-mismatch",
      "The readiness evidence digest does not match its canonical content.",
    );
  }
  assertEvidenceCurrent(evidence, evaluatedAt, "The readiness artifact", "issuedAt");

  const environments = Object.fromEntries(
    input.target.environments.map((environment) => [
      environment.name,
      environment.subscriptionId.toLowerCase(),
    ]),
  );
  const secondary =
    input.regionalPlan.requestedRegionalMode === "single-region-ready"
      ? null
      : input.regionalPlan.secondaryRecommendation?.region ?? null;
  const expectedSubject = {
    planId: input.planId,
    tenantId: input.target.tenantId.toLowerCase(),
    prodSubscriptionId: environments.prod,
    nonprodSubscriptionId: environments.nonprod,
    profileVersion: input.workloadPlan.profileVersion,
    computeProfile: input.workloadPlan.computeProfile,
    profileExtensions: [...input.workloadPlan.profileExtensions].sort(),
    regionalMode: input.regionalPlan.requestedRegionalMode,
    primaryRegion: input.regionalPlan.selectedPrimary?.region,
    secondaryRegion: secondary,
  };
  const actualSubject = {
    ...evidence.subject,
    profileExtensions: [...evidence.subject.profileExtensions].sort(),
  };
  if (canonicalJson(actualSubject) !== canonicalJson(expectedSubject)) {
    readinessFail(
      "readiness.evidence.scope-mismatch",
      "The readiness evidence subject does not match the exact plan, target, profiles, and regions.",
    );
  }

  const preflight = evidence.codeEvidence.preflight;
  assertEvidenceCurrent(preflight, evaluatedAt, "Authoritative preflight evidence", "observedAt");
  if (preflight.status !== "pass") {
    readinessFail(
      "readiness.preflight.blocked",
      "Authoritative preflight evidence is missing or blocked.",
    );
  }

  const topology = evidence.codeEvidence.subscriptionTopology;
  assertEvidenceCurrent(
    topology,
    evaluatedAt,
    "Subscription topology decision",
    "generatedAt",
    READINESS_CHECK_IDS.topology,
  );
  if (topologyDecisionDigest(topology) !== topology.decisionDigest) {
    readinessFail(
      "readiness.topology.digest-mismatch",
      "The subscription topology decision digest does not match its canonical content.",
    );
  }
  const expectedTopologyEnvironments = input.target.environments
    .map((environment) => ({
      name: environment.name,
      subscriptionId: environment.subscriptionId.toLowerCase(),
    }))
    .sort((left, right) => left.name.localeCompare(right.name));
  if (
    topology.tenantId !== expectedSubject.tenantId ||
    canonicalJson(topology.environments) !==
      canonicalJson(expectedTopologyEnvironments)
  ) {
    readinessFail(
      "readiness.topology.scope-mismatch",
      "The subscription topology decision does not match the exact tenant and environment mapping.",
    );
  }
  const expectedTopologyState =
    expectedSubject.prodSubscriptionId === expectedSubject.nonprodSubscriptionId
      ? "one-subscription-startup"
      : "separate-prod-nonprod-subscriptions";
  if (topology.subscriptionTopology.state !== expectedTopologyState) {
    readinessFail(
      "readiness.topology.unsupported",
      "The subscription topology is missing, ambiguous, or inconsistent with the selected environments.",
    );
  }
  if (
    topology.benefitAssociation.state ===
    "benefits-on-different-subscription-or-billing-profile"
  ) {
    readinessFail(
      "readiness.topology.benefit-target-mismatch",
      "Observed benefit evidence points outside the selected deployment target; rerun preflight after support resolves it.",
      READINESS_CHECK_IDS.support,
    );
  }

  const workspaceDecision = evidence.codeEvidence.defenderWorkspacePlacement;
  if (!workspaceDecision) {
    readinessFail(
      "readiness.defender-workspace.required",
      "A deterministic Defender workspace placement decision is required.",
    );
  }
  assertEvidenceCurrent(
    workspaceDecision,
    evaluatedAt,
    "Defender workspace placement decision",
    "generatedAt",
    READINESS_CHECK_IDS.defenderWorkspace,
  );
  if (
    defenderWorkspaceDecisionDigest(workspaceDecision) !==
    workspaceDecision.decisionDigest
  ) {
    readinessFail(
      "readiness.defender-workspace.digest-mismatch",
      "The Defender workspace placement decision digest does not match its canonical content.",
    );
  }
  if (
    workspaceDecision.status === "blocked" ||
    (workspaceDecision.defenderWorkspaceRequired &&
      workspaceDecision.status !== "ready")
  ) {
    readinessFail(
      "readiness.defender-workspace.blocked",
      "The Defender workspace placement decision is blocked or ambiguous.",
    );
  }
  if (
    workspaceDecision.tenantId !== expectedSubject.tenantId ||
    workspaceDecision.subscriptionId !== expectedSubject.prodSubscriptionId ||
    workspaceDecision.primaryRegion !== expectedSubject.primaryRegion ||
    canonicalJson(workspaceDecision.targetSubscriptionIds) !==
      canonicalJson(
        [
          ...new Set([
            expectedSubject.prodSubscriptionId,
            expectedSubject.nonprodSubscriptionId,
          ]),
        ].sort(),
      )
  ) {
    readinessFail(
      "readiness.defender-workspace.scope-mismatch",
      "The Defender workspace decision does not match the selected tenant, production subscription, and primary region.",
    );
  }
  if (workspaceDecision.defenderWorkspaceRequired) {
    const decisionExpiry = Date.parse(workspaceDecision.expiresAt);
    const evidenceExpiries = [
      workspaceDecision.evidence.policyEvidenceExpiresAt,
      workspaceDecision.evidence.serviceSupportEvidenceExpiresAt,
      workspaceDecision.evidence.dataResidencyEvidenceExpiresAt,
      ...(workspaceDecision.placement.mode === "existing"
        ? [workspaceDecision.evidence.workspaceEvidenceExpiresAt]
        : []),
      ...(workspaceDecision.evidence.centralWorkspaceEvidenceDigest
        ? [workspaceDecision.evidence.centralWorkspaceEvidenceExpiresAt]
        : []),
    ];
    if (
      evidenceExpiries.some(
        (value) =>
          !value ||
          Date.parse(value) <= evaluatedAt ||
          Date.parse(value) < decisionExpiry,
      )
    ) {
      readinessFail(
        "readiness.defender-workspace.stale",
        "Defender workspace policy, service, residency, or workspace evidence is stale or expires before the decision.",
      );
    }
  }
  const inputWorkspaceDecision =
    input.deployment?.defenderWorkspacePlacement ?? null;
  if (
    inputWorkspaceDecision &&
    (inputWorkspaceDecision.decisionId !== workspaceDecision.decisionId ||
      inputWorkspaceDecision.decisionDigest !== workspaceDecision.decisionDigest ||
      inputWorkspaceDecision.paidPlanSelectionDigest !==
        workspaceDecision.paidPlanSelectionDigest)
  ) {
    readinessFail(
      "readiness.defender-workspace.selection-mismatch",
      "The IaC workspace decision or paid-plan selection differs from readiness evidence.",
    );
  }

  const support = evidence.humanAttestations.startupBillingSupport;
  assertEvidenceCurrent(
    support,
    evaluatedAt,
    "Microsoft for Startups billing and support confirmation",
    "attestedAt",
    READINESS_CHECK_IDS.support,
  );
  if (
    support.attestationVersion !== "2.0.0" ||
    support.status !== "confirmed" ||
    support.topologyDecisionId !== topology.decisionId ||
    support.topologyDecisionDigest !== topology.decisionDigest
  ) {
    readinessFail(
      "readiness.support.confirmation-required",
      "An explicit current Microsoft for Startups or Azure Billing confirmation bound to the exact topology decision is required.",
    );
  }

  const reviewGates = [
    {
      evidence: evidence.humanAttestations.externalReviews.security,
      label: "Security review",
      code: "readiness.review.security-approved",
    },
    {
      evidence: evidence.humanAttestations.externalReviews.azureArchitecture,
      label: "Azure architecture review",
      code: "readiness.review.azure-architecture-approved",
    },
    {
      evidence: evidence.humanAttestations.externalReviews.iacParity,
      label: "Bicep/Terraform parity review",
      code: "readiness.review.iac-parity-approved",
    },
  ];
  for (const review of reviewGates) {
    assertEvidenceCurrent(
      review.evidence,
      evaluatedAt,
      review.label,
      "attestedAt",
      READINESS_ERROR_CHECK_IDS.get(review.code),
    );
    if (
      review.evidence.attestationVersion !== "1.0.0" ||
      review.evidence.status !== "approved"
    ) {
      readinessFail(
        review.code,
        `${review.label} requires an explicit current approved attestation reference.`,
      );
    }
  }

  const owner = evidence.humanAttestations.failoverOwner;
  assertEvidenceCurrent(
    owner,
    evaluatedAt,
    "Failover owner attestation",
    "attestedAt",
    READINESS_CHECK_IDS.failoverOwner,
  );
  if (
    owner.status !== "confirmed" ||
    !owner.ownerReference ||
    !owner.roleReference ||
    (expectedSubject.regionalMode === "cool-infrastructure" &&
      !owner.roleDisplayName)
  ) {
    readinessFail(
      "readiness.failover.owner-required",
      "A current named failover owner reference and role reference are required.",
    );
  }

  const selectedProfiles = [
    input.workloadPlan.computeProfile,
    ...input.workloadPlan.profileExtensions,
  ];
  const recovery = evidence.humanAttestations.recoveryMeasurements;
  assertExactEvidenceSet(
    recovery,
    selectedProfiles,
    (measurement) => measurement.profileId,
    "readiness.recovery.measurement-required",
    "Recovery measurements",
  );
  const targetRto = input.regionalPlan.recoveryTargets.rtoMinutes;
  const targetRpo = input.regionalPlan.recoveryTargets.rpoMinutes;
  if (!Number.isFinite(targetRto) || !Number.isFinite(targetRpo)) {
    readinessFail(
      "readiness.recovery.target-required",
      "Explicit RTO and RPO targets are required before readiness can pass.",
    );
  }
  for (const measurement of recovery) {
    assertEvidenceCurrent(
      measurement,
      evaluatedAt,
      `Recovery measurement for ${measurement.profileId}`,
      "attestedAt",
      READINESS_CHECK_IDS.recoveryObjectives,
    );
    if (
      measurement.status !== "met" ||
      measurement.targetRtoMinutes !== targetRto ||
      measurement.targetRpoMinutes !== targetRpo ||
      measurement.measuredRtoMinutes > targetRto ||
      measurement.measuredRpoMinutes > targetRpo
    ) {
      readinessFail(
        "readiness.recovery.objective-unmet",
        `Measured recovery for ${measurement.profileId} does not meet the selected RTO/RPO.`,
      );
    }
  }

  const serviceTests = evidence.humanAttestations.serviceRecoveryTests;
  assertExactEvidenceSet(
    serviceTests,
    input.workloadPlan.profileExtensions,
    (test) => test.profileExtension,
    "readiness.recovery.service-test-required",
    "Service-specific recovery tests",
  );
  for (const test of serviceTests) {
    assertEvidenceCurrent(
      test,
      evaluatedAt,
      `Recovery test for ${test.profileExtension}`,
      "attestedAt",
      READINESS_CHECK_IDS.serviceRecovery,
    );
    if (test.status !== "pass") {
      readinessFail(
        "readiness.recovery.service-test-failed",
        `The ${test.profileExtension} recovery test has not passed.`,
      );
    }
  }

  const expectedRegions = [
    `primary:${expectedSubject.primaryRegion}`,
    ...(secondary ? [`secondary:${secondary}`] : []),
  ];
  const regional = evidence.codeEvidence.regional;
  assertExactEvidenceSet(
    regional,
    expectedRegions,
    (item) => `${item.role}:${item.region}`,
    "readiness.region.scope-mismatch",
    "Regional evidence",
  );
  for (const item of regional) {
    assertEvidenceCurrent(
      item,
      evaluatedAt,
      `${item.role} regional evidence`,
      "observedAt",
      READINESS_CHECK_IDS.region,
    );
    if (item.status !== "pass") {
      readinessFail(
        "readiness.region.blocked",
        `${item.role} regional evidence is not passing.`,
      );
    }
  }

  const cost = evidence.humanAttestations.coolFootprintCost;
  const recoveryExercise = evidence.humanAttestations.recoveryExercise;
  if (expectedSubject.regionalMode === "cool-infrastructure") {
    if (!cost) {
      readinessFail(
        "readiness.cost.provenance-required",
        "Cool-infrastructure readiness requires a current cost range and provenance reference.",
      );
    }
    assertEvidenceCurrent(
      cost,
      evaluatedAt,
      "Cool-footprint cost attestation",
      "attestedAt",
      READINESS_CHECK_IDS.coolCost,
    );
    if (
      cost.status !== "confirmed" ||
      !cost.provenanceReference ||
      cost.minimum > cost.maximum
    ) {
      readinessFail(
        "readiness.cost.range-invalid",
        "The cool-footprint cost range or provenance is invalid.",
      );
    }
    const selectedCost = input.regionalPlan.costAssumptions.secondaryBaseline;
    const primaryMonthlyCost =
      input.regionalPlan.costAssumptions.selectedPrimaryEstimate;
    const projectedPercent =
      primaryMonthlyCost > 0 ? (selectedCost.maximum / primaryMonthlyCost) * 100 : null;
    if (
      cost.currency !== input.regionalPlan.costAssumptions.currency ||
      cost.minimum !== selectedCost.minimum ||
      cost.maximum !== selectedCost.maximum ||
      cost.primaryMonthlyCost !== primaryMonthlyCost ||
      !Number.isFinite(projectedPercent) ||
      Math.abs(cost.projectedPercent - projectedPercent) > 0.000001
    ) {
      readinessFail(
        "readiness.cost.scope-mismatch",
        "The cool-footprint cost attestation does not match the selected regional plan.",
      );
    }
    if (cost.projectedPercent > cost.ceilingPercent) {
      readinessFail(
        "readiness.cost.ceiling-exceeded",
        "The reviewed cool-footprint maximum exceeds its recurring-cost ceiling.",
        READINESS_CHECK_IDS.coolCost,
      );
    }
    if (!recoveryExercise) {
      readinessFail(
        "readiness.recovery.exercise-required",
        "Cool-infrastructure readiness requires a current recovery exercise attestation.",
      );
    }
    assertEvidenceCurrent(
      recoveryExercise,
      evaluatedAt,
      "Cool-foundation recovery exercise",
      "attestedAt",
      READINESS_CHECK_IDS.recoveryExercise,
    );
    if (
      recoveryExercise.status !== "pass" ||
      !recoveryExercise.exerciseReference
    ) {
      readinessFail(
        "readiness.recovery.exercise-failed",
        "The cool-foundation recovery exercise has not passed.",
      );
    }
  } else if (cost !== null || recoveryExercise !== null) {
    readinessFail(
      "readiness.cost.scope-mismatch",
      "Cool-footprint cost and recovery-exercise evidence must be omitted when cool-infrastructure is not selected.",
    );
  }

  const foundry = evidence.codeEvidence.foundry;
  if (input.workloadPlan.profileExtensions.includes("foundry")) {
    assertExactEvidenceSet(
      foundry,
      expectedRegions,
      (item) => `${item.role}:${item.region}`,
      "readiness.foundry.evidence-required",
      "Foundry evidence",
    );
    for (const item of foundry) {
      assertEvidenceCurrent(
        item,
        evaluatedAt,
        `${item.role} Foundry evidence`,
        "observedAt",
        READINESS_CHECK_IDS.foundry,
      );
      if (
        item.status !== "pass" ||
        !item.modelReference ||
        !item.modelVersion ||
        !item.deploymentType ||
        item.availableQuota < item.requiredQuota
      ) {
        readinessFail(
          "readiness.foundry.blocked",
          "Foundry model version, deployment type, and sufficient current quota are required.",
        );
      }
    }
  } else if (foundry.length !== 0) {
    readinessFail(
      "readiness.foundry.scope-mismatch",
      "Foundry evidence is only valid when the Foundry profile extension is selected.",
    );
  }

  return evidence;
}

