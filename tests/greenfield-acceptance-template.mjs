#!/usr/bin/env node

import assert from "node:assert/strict";

let input = "";
for await (const chunk of process.stdin) input += chunk;
const template = JSON.parse(input);
const top = Object.values(template.resources);
assert.deepEqual(top.map(r => r.type).sort(), ["Microsoft.Resources/deployments", "Microsoft.Resources/resourceGroups"]);
const group = top.find(r => r.type === "Microsoft.Resources/resourceGroups");
assert.equal(group.tags, "[variables('tags')]");
assert.equal(template.variables.tags.project, "sslz-acceptance");
const deployment = top.find(r => r.type === "Microsoft.Resources/deployments");
assert.equal(deployment.properties.mode, "Incremental");
const resources = Object.values(deployment.properties.template.resources);
const find = type => {
  const found = resources.filter(r => r.type === type);
  assert.equal(found.length, 1, type);
  return found[0];
};
assert.equal(resources.length, 12);
const storage = find("Microsoft.Storage/storageAccounts");
assert.equal(storage.sku.name, "Standard_LRS");
assert.equal(storage.properties.allowSharedKeyAccess, false);
assert.equal(storage.properties.allowBlobPublicAccess, false);
assert.equal(storage.properties.publicNetworkAccess, "Disabled");
assert.equal(storage.properties.networkAcls.bypass, "None");
const blobs = find("Microsoft.Storage/storageAccounts/blobServices");
assert.equal(blobs.properties.isVersioningEnabled, true);
assert.equal(blobs.properties.deleteRetentionPolicy.enabled, true);
const container = find("Microsoft.Storage/storageAccounts/blobServices/containers");
assert.equal(container.properties.publicAccess, "None");
const assignment = find("Microsoft.Authorization/roleAssignments");
assert.match(assignment.properties.roleDefinitionId, /ba92f5b4-2d11-453d-a403-e96b0029c9fe/);
assert.match(assignment.scope, /acceptance/);
assert.equal(assignment.properties.principalType, "ServicePrincipal");
find("Microsoft.ManagedIdentity/userAssignedIdentities");
const network = find("Microsoft.Network/virtualNetworks");
assert.deepEqual(network.properties.addressSpace.addressPrefixes, ["10.242.0.0/24"]);
assert.equal(network.properties.subnets[0].properties.delegations[0].properties.serviceName, "Microsoft.App/environments");
assert.equal(network.properties.subnets[0].properties.addressPrefix, "10.242.0.0/27");
assert.equal(network.properties.subnets[1].properties.privateEndpointNetworkPolicies, "Disabled");
const endpoint = find("Microsoft.Network/privateEndpoints");
assert.deepEqual(endpoint.properties.privateLinkServiceConnections[0].properties.groupIds, ["blob"]);
find("Microsoft.Network/privateDnsZones");
assert.equal(find("Microsoft.Network/privateDnsZones/virtualNetworkLinks").properties.registrationEnabled, false);
find("Microsoft.Network/privateEndpoints/privateDnsZoneGroups");
const environment = find("Microsoft.App/managedEnvironments");
assert.equal(environment.properties.workloadProfiles[0].workloadProfileType, "Consumption");
assert.equal(environment.properties.appLogsConfiguration, undefined);
assert.match(environment.properties.infrastructureResourceGroup, /managedGroupName/);
const app = find("Microsoft.App/containerApps");
assert.equal(app.identity.type, "UserAssigned");
assert.equal(app.properties.configuration.ingress.allowInsecure, false);
assert.equal(app.properties.configuration.ingress.targetPort, 8080);
assert.deepEqual(app.properties.template.scale, { minReplicas: 1, maxReplicas: 1 });
assert.equal(app.properties.template.containers.length, 1);
const service = app.properties.template.containers[0];
assert.equal(service.image, "[parameters('image')]");
assert.deepEqual(service.env.map(e => e.name).sort(), ["AZURE_CLIENT_ID", "BLOB_ACCOUNT_URL", "BLOB_CONTAINER"]);
assert.equal(service.probes.find(p => p.type === "Readiness").httpGet.path, "/readyz");
assert.equal(service.probes.find(p => p.type === "Liveness").httpGet.path, "/healthz");
assert.deepEqual(service.resources, { cpu: "[json('0.25')]", memory: "0.5Gi" });
console.log("Compiled acceptance graph passed: new group, private blob, scoped identity, bounded Container App, and probes.");
